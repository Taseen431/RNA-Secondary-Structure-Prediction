// ----------------------------- CSV ----------------------------------------
void initCSV(const string &path) {
    ifstream in(path.c_str());
    bool needHeader = (!in.good() || in.peek() == char_traits<char>::eof());
    in.close();
    if (needHeader) {
        ofstream out(path.c_str());
        out << "RunID,DateTime,Algorithm,SequenceID,Iteration,Energy,PredictedStructure,"
               "TP,FP,FN,Sensitivity,Specificity,Fmeasure,INF\n";
        out.close();
    }
}

void appendToCSV(const string &path, const string &runID,
                 const string &dateTime, RNA_Core *solver) {
    ofstream out(path.c_str(), ios::app);
    out << fixed << setprecision(2);
    for (const auto &rec : solver->iterationLog) {
        out << runID << "," << dateTime << "," << solver->algorithm << ","
            << solver->sequenceID << "," << rec.iteration << "," << rec.energy << ","
            << rec.structure << "," << rec.metrics.TP << "," << rec.metrics.FP << ","
            << rec.metrics.FN << "," << rec.metrics.sensitivity << ","
            << rec.metrics.specificity << "," << rec.metrics.fmeasure << ","
            << rec.metrics.inf << "\n";
    }
    out.close();
}

// ----------------------------- Result text (summary) ----------------------

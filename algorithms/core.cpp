double RNA_Core::calculateFreeEnergy(const string &structure) {
    if (structure.empty() || count(structure.begin(), structure.end(), '(') == 0) return 0.0;

    vector<int> stack;
    vector<pair<int, int>> pairList;
    for (int i = 0; i < (int)structure.size(); i++) {
        if (structure[i] == '(') stack.push_back(i);
        else if (structure[i] == ')') {
            if (!stack.empty()) { int j = stack.back(); stack.pop_back(); pairList.push_back({j, i}); }
        }
    }
    sort(pairList.begin(), pairList.end());

    double total_energy = 0.0;

    // Pair type 0 (non-ACGU, e.g. the N residues in seq10) and type 7 (ACGU but
    // non-canonical) cannot occur in a structure built by buildStructure, which
    // only places isValidPair stems.  They arise solely when scoring an externally
    // supplied structure -- a CRW reference -- where they are real observed pairs.
    // Charging +50 / +1.5 for them therefore penalised the true structure and
    // nothing else: seq10's reference picked up +100 from two N-containing pairs
    // alone.  Both are neutral now, which leaves predicted energies untouched and
    // makes reference and prediction comparable on the same scale.
    const double PEN_INVALID  = 0.0;   // was 50.0
    const double PEN_NONCANON = 0.0;   // was 1.5

    auto getInnerPairs = [&](int L, int R) {
        vector<pair<int, int>> inner;
        int m = L;
        while (m <= R) {
            bool found = false;
            for (const auto& p : pairList) {
                if (p.first == m) { inner.push_back(p); m = p.second + 1; found = true; break; }
            }
            if (!found) m++;
        }
        return inner;
    };
    auto isTerminalAUGU = [&](char a, char b) {
        int t = getPairType(a, b);
        return (t == 1 || t == 2 || t == 5 || t == 6);
    };

    // ---- helix-end stabilisation in multibranch and external loops ----
    // The loop is walked as a ring of helix ends.  Each element is the pair
    // (a, b) in the order the loop enters and leaves that helix, so the base
    // preceding a and the base following b are the ones facing this loop.  The
    // closing pair of a multiloop is entered at j and left at i -- reversed --
    // which makes it uniform with the branches.
    //
    // At each interface between consecutive helices:
    //   gap == 0  ->  the helices are flush and stack coaxially.  Turner and
    //                 RNAstructure score a flush coaxial stack with the ordinary
    //                 nearest-neighbour stacking table, so getStackingEnergy is
    //                 reused and no new parameters are introduced.
    //   gap  > 0  ->  the intervening base(s) dangle: a 3' dangle on the helix
    //                 to the left and a 5' dangle on the helix to the right.
    // Deciding per interface, rather than awarding both dangles at every helix
    // unconditionally, is what stops a flush interface from being paid for twice
    // -- at gap == 0 the "dangling" base is in fact paired into the next helix.
    typedef pair<int, int> HelixEnd;
    auto endEnergy = [&](const vector<HelixEnd> &ring, bool cyclic) {
        double e = 0.0;
        int sz = (int)ring.size();
        int last = cyclic ? sz : sz - 1;
        for (int t = 0; t < last; t++) {
            const HelixEnd &X = ring[t];
            const HelixEnd &Y = ring[(t + 1) % sz];
            int gap = Y.first - X.second - 1;
            if (gap == 0) {
                e += getStackingEnergy(sequence[X.second], sequence[X.first],
                                       sequence[Y.first],  sequence[Y.second]);
            } else {
                int tX = getPairType(sequence[X.first], sequence[X.second]);
                int tY = getPairType(sequence[Y.first], sequence[Y.second]);
                int b3 = (X.second + 1 < n) ? baseIndex(sequence[X.second + 1]) : BASE_N;
                int b5 = (Y.first  - 1 >= 0) ? baseIndex(sequence[Y.first  - 1]) : BASE_N;
                e += dangle3DG[tX][b3] + dangle5DG[tY][b5];
            }
        }
        if (!cyclic && sz > 0) {                 // external loop: two free ends
            const HelixEnd &F = ring.front();
            const HelixEnd &L = ring.back();
            int tF = getPairType(sequence[F.first],  sequence[F.second]);
            int tL = getPairType(sequence[L.first],  sequence[L.second]);
            int b5 = (F.first  - 1 >= 0) ? baseIndex(sequence[F.first  - 1]) : BASE_N;
            int b3 = (L.second + 1 < n)  ? baseIndex(sequence[L.second + 1]) : BASE_N;
            e += dangle5DG[tF][b5] + dangle3DG[tL][b3];
        }
        return e;
    };

    vector<pair<pair<int, int>, vector<pair<int, int>>>> loops;
    for (const auto& p : pairList)
        loops.push_back({{p.first, p.second}, getInnerPairs(p.first + 1, p.second - 1)});
    loops.push_back({{-1, (int)structure.size()}, getInnerPairs(0, (int)structure.size() - 1)});

    for (const auto& loop : loops) {
        int i = loop.first.first, j = loop.first.second;
        const auto& inner = loop.second;
        int k = (int)inner.size();

        if (i == -1) {
            vector<HelixEnd> ring;
            for (const auto& p : inner) {
                if (isTerminalAUGU(sequence[p.first], sequence[p.second])) total_energy += 0.5;
                ring.push_back(HelixEnd(p.first, p.second));
            }
            total_energy += endEnergy(ring, false);   // external loop: not a ring
            continue;
        }

        int parent_type = getPairType(sequence[i], sequence[j]);

        if (k == 0) {
            int size = j - i - 1;
            double energy = 0.0;
            // Loops of fewer than 3 unpaired bases cannot close: kept as a
            // geometric guard.  Verified never to fire on any of the 10
            // references, so it costs the true structure nothing.
            if (size < 3) energy += 50.0;
            else energy += loopInitiation(size, LOOP_HAIRPIN);
            // Triloops take no terminal mismatch, only the AU/GU charge; from
            // size 4 the mismatch table supplies both (see its header note).
            if (size == 3) {
                if (isTerminalAUGU(sequence[i], sequence[j])) energy += 0.5;
            } else if (size > 3) {
                energy += mismatchHairpinDG[parent_type]
                                           [baseIndex(sequence[i + 1])]
                                           [baseIndex(sequence[j - 1])];
            }
            if (parent_type == 0) energy += PEN_INVALID;
            else if (parent_type == 7) energy += PEN_NONCANON;
            total_energy += energy;
        }
        else if (k == 1) {
            int u = inner[0].first, v = inner[0].second;
            int size_left = u - i - 1, size_right = j - v - 1;
            double energy = 0.0;
            int inner_type = getPairType(sequence[u], sequence[v]);

            if (size_left == 0 && size_right == 0) {
                energy += getStackingEnergy(sequence[i], sequence[j], sequence[u], sequence[v]);
                if (parent_type == 0 || inner_type == 0) energy += PEN_INVALID;
            }
            else if (size_left == 0 || size_right == 0) {
                int size = size_left + size_right;
                energy += loopInitiation(size, LOOP_BULGE);
                // A single-nucleotide bulge does not interrupt the helix, so the
                // stack is retained (Turner 2004, unchanged from before).
                if (size == 1) energy += getStackingEnergy(sequence[i], sequence[j], sequence[u], sequence[v]);
                if (isTerminalAUGU(sequence[i], sequence[j])) energy += 0.5;
                if (isTerminalAUGU(sequence[u], sequence[v])) energy += 0.5;
                if (parent_type == 7) energy += PEN_NONCANON;
                if (inner_type == 7) energy += PEN_NONCANON;
                if (parent_type == 0 || inner_type == 0) energy += PEN_INVALID;
            }
            else {
                int size = size_left + size_right;
                // Sizes 2 (1x1) and 3 (1x2) are handled by Turner's dedicated
                // int11 / int21 tables, which the length model does not cover;
                // the existing constants are kept for them.
                if (size == 2) energy += 0.8;
                else if (size == 3) energy += 1.3;
                else {
                    // Turner NINIO asymmetry: min(3.0, 0.6 * |n1 - n2|),
                    // from the NINIO line of rna_turner2004.par (m=60, max=300).
                    int asymmetry = abs(size_left - size_right);
                    double ninio = 0.6 * asymmetry;
                    if (ninio > 3.0) ninio = 3.0;
                    energy += loopInitiation(size, LOOP_INTERNAL) + ninio;
                }
                if (size < 4) {
                    // 1x1 and 1x2 loops: no generic mismatch, AU/GU charge only.
                    if (isTerminalAUGU(sequence[i], sequence[j])) energy += 0.5;
                    if (isTerminalAUGU(sequence[u], sequence[v])) energy += 0.5;
                } else {
                    // Both closing pairs carry a terminal mismatch; the inner one
                    // is read in reversed orientation, as seen from the loop.
                    energy += mismatchInternalDG[parent_type]
                                                [baseIndex(sequence[i + 1])]
                                                [baseIndex(sequence[j - 1])];
                    energy += mismatchInternalDG[getPairType(sequence[v], sequence[u])]
                                                [baseIndex(sequence[v + 1])]
                                                [baseIndex(sequence[u - 1])];
                }
                if (parent_type == 7) energy += PEN_NONCANON;
                if (inner_type == 7) energy += PEN_NONCANON;
                if (parent_type == 0 || inner_type == 0) energy += PEN_INVALID;
            }
            total_energy += energy;
        }
        else {
            // Turner 2004 multibranch initiation (NNDB, rna_2004_multibranch_loops):
            //   dG = a + b*[average asymmetry] + c*[number of branching helices]
            //   a = 9.25, b = 0.91, c = -0.63
            //   average asymmetry = min[2.0, mean difference in unpaired
            //                            nucleotides on each side of each helix]
            // The strain term for three-way loops carrying fewer than two unpaired
            // nucleotides is omitted: NNDB states the rule but publishes no value.
            // Previously this was 10.1 + 0.4*(k+1), which combined the large 2004
            // initiation with the POSITIVE per-helix slope of the 1999 linear model
            // and so charged extra for every branch instead of crediting it.
            int helices = k + 1;
            vector<int> gaps(k + 1, 0);
            gaps[0] = inner[0].first - i - 1;
            for (int t = 1; t < k; t++) gaps[t] = inner[t].first - inner[t - 1].second - 1;
            gaps[k] = j - inner[k - 1].second - 1;

            double asymSum = abs(gaps[0] - gaps[k]);                 // the closing helix
            for (int t = 0; t < k; t++) asymSum += abs(gaps[t] - gaps[t + 1]);
            double avgAsym = asymSum / helices;
            if (avgAsym > 2.0) avgAsym = 2.0;

            double energy = 9.25 + 0.91 * avgAsym - 0.63 * helices;
            if (isTerminalAUGU(sequence[i], sequence[j])) energy += 0.5;

            // ring order: closing helix entered at j and left at i, then the
            // branches in sequence order.  Neighbour bases are then uniformly
            // (a - 1) and (b + 1) for every element, closing pair included.
            vector<HelixEnd> ring;
            ring.push_back(HelixEnd(j, i));
            for (const auto& p : inner) {
                if (isTerminalAUGU(sequence[p.first], sequence[p.second])) energy += 0.5;
                ring.push_back(HelixEnd(p.first, p.second));
            }
            energy += endEnergy(ring, true);
            if (parent_type == 0) energy += PEN_INVALID;
            else if (parent_type == 7) energy += PEN_NONCANON;
            for (const auto& p : inner) {
                int in_type = getPairType(sequence[p.first], sequence[p.second]);
                if (in_type == 0) energy += PEN_INVALID;
                else if (in_type == 7) energy += PEN_NONCANON;
            }
            total_energy += energy;
        }
    }
    return total_energy;
}

// ----------------------------- Structure construction ---------------------
string RNA_Core::buildStructure(const Individual &B) {
    string structure(n, '.');
    vector<bool> used(n, false);
    vector<pair<int, int>> acceptedPairs;
    for (int stemIdx : B) {
        if (stemIdx < 1 || stemIdx > (int)stemList.size()) continue;
        const Stem &s = stemList[stemIdx - 1];
        int len = s.length;
        if (len <= 0) continue;
        bool conflict = false;
        for (int k = 0; k < len; k++) {
            int openPos = s.start + k, closePos = s.end - k;
            if (openPos < 0 || closePos >= n || closePos - openPos < 4) { conflict = true; break; }
            if (used[openPos] || used[closePos]) { conflict = true; break; }
            for (const auto &p : acceptedPairs) {
                int i2 = p.first;
                int j2 = p.second;
                if ((openPos < i2 && i2 < closePos && closePos < j2) ||
                    (i2 < openPos && openPos < j2 && j2 < closePos)) {
                    conflict = true;
                    break;
                }
            }
            if (conflict) break;
        }
        if (conflict) continue;
        for (int k = 0; k < len; k++) {
            int openPos = s.start + k, closePos = s.end - k;
            structure[openPos] = '('; structure[closePos] = ')';
            used[openPos] = used[closePos] = true;
            acceptedPairs.push_back({openPos, closePos});
        }
    }
    return structure;
}

// ----------------------------- Optimize (dedup / range guard) -------------
Individual RNA_Core::optimizeButterfly(const Individual &B) {
    Individual result;
    unordered_set<int> seen;
    vector<bool> used(n, false);

    for (int val : B) {
        if (val < 1 || val > (int)stemList.size()) continue;
        if (seen.find(val) == seen.end()) {
            const Stem &s = stemList[val - 1];
            bool conflict = false;
            for (int k = 0; k < s.length; k++) {
                int openPos = s.start + k;
                int closePos = s.end - k;
                if (openPos < 0 || closePos >= n || openPos >= closePos) { conflict = true; break; }
                if (used[openPos] || used[closePos]) { conflict = true; break; }
            }
            if (!conflict) {
                seen.insert(val);
                result.push_back(val);
                for (int k = 0; k < s.length; k++) {
                    used[s.start + k] = used[s.end - k] = true;
                }
            }
        }
    }

    if (result.empty()) result.push_back(randInt(1, max(1, (int)stemList.size())));
    return result;
}

double RNA_Core::calculateFitness(const Individual &B, string &structOut) {
    structOut = buildStructure(B);
    return calculateFreeEnergy(structOut);
}

// ----------------------------- Random individual --------------------------
Individual RNA_Core::randomPermutation() {
    int m = (int)stemList.size();
    if (m == 0) return {0};
    vector<int> perm(m);
    for (int i = 0; i < m; i++) perm[i] = i + 1;
    shuffle(perm.begin(), perm.end(), rng);

    Individual result;
    vector<bool> used(n, false);
    for (int stemIdx : perm) {
        const Stem &s = stemList[stemIdx - 1];
        bool conflict = false;
        for (int k = 0; k < s.length; k++) {
            int openPos = s.start + k;
            int closePos = s.end - k;
            if (openPos < 0 || closePos >= n || openPos >= closePos) { conflict = true; break; }
            if (used[openPos] || used[closePos]) { conflict = true; break; }
        }
        if (!conflict) {
            result.push_back(stemIdx);
            for (int k = 0; k < s.length; k++) {
                used[s.start + k] = used[s.end - k] = true;
            }
        }
        if ((int)result.size() >= MAX_LEN) break;
    }
    if (result.empty()) result.push_back(randInt(1, m));
    return result;
}

// ----------------------------- Hill climb refinement ----------------------
void RNA_Core::hillClimbBest() {
    bool improved = true;
    while (improved) {
        improved = false;
        for (int s = 1; s <= (int)stemList.size(); s++) {
            if (find(globalBest.begin(), globalBest.end(), s) == globalBest.end()) {
                Individual temp = globalBest;
                temp.push_back(s);
                temp = optimizeButterfly(temp);
                string st;
                double fe = calculateFitness(temp, st);
                if (fe < globalBestFE) { globalBestFE = fe; globalBest = temp; globalBestStructure = st; improved = true; }
            }
        }
        for (size_t i = 0; i < globalBest.size(); i++) {
            Individual temp = globalBest;
            temp.erase(temp.begin() + i);
            if (temp.empty()) continue;
            string st;
            double fe = calculateFitness(temp, st);
            if (fe < globalBestFE) { globalBestFE = fe; globalBest = temp; globalBestStructure = st; improved = true; break; }
        }
    }
}

// ----------------------------- Metrics ------------------------------------
vector<pair<int,int>> RNA_Core::extractPairs(const string &structure) {
    vector<pair<int,int>> pairsVec;
    vector<int> stack;
    for (int i = 0; i < (int)structure.size(); i++) {
        if (structure[i] == '(') stack.push_back(i);
        else if (structure[i] == ')') {
            if (!stack.empty()) { int j = stack.back(); stack.pop_back(); pairsVec.push_back({min(i,j), max(i,j)}); }
        }
    }
    return pairsVec;
}

Metrics RNA_Core::calculateMetrics(const string &predicted, const string &known) {
    Metrics m;
    auto predPairs = extractPairs(predicted);
    auto knownPairs = extractPairs(known);
    set<pair<int,int>> predSet(predPairs.begin(), predPairs.end());
    set<pair<int,int>> knownSet(knownPairs.begin(), knownPairs.end());
    for (auto &p : predSet) { if (knownSet.count(p)) m.TP++; else m.FP++; }
    for (auto &p : knownSet) if (!predSet.count(p)) m.FN++;
    double TP = m.TP, FP = m.FP, FN = m.FN;
    m.sensitivity = (TP + FN > 0) ? (TP / (TP + FN)) * 100.0 : 0.0;
    m.specificity = (TP + FP > 0) ? (TP / (TP + FP)) * 100.0 : 0.0;
    if (m.sensitivity + m.specificity > 0)
        m.fmeasure = (2.0 * m.sensitivity * m.specificity) / (m.sensitivity + m.specificity);
    else m.fmeasure = 0.0;
    m.inf = sqrt(m.sensitivity * m.specificity);
    return m;
}

Metrics RNA_Core::evaluateResult() {
    return calculateMetrics(globalBestStructure, knownStructure);
}

// ----------------------------- Per-iteration logging ----------------------

// Beyond the measured range, Jacobson-Stockmayer as NNDB specifies:
//   dG(n) = dG(30) + 1.75 * R * T * ln(n/30),  R*T = 0.6163 kcal/mol at 37 C
static double loopInitiation(int size, int col) {
    if (size < 1) return 0.0;
    if (size <= 30) return turnerLoopDG[size][col];
    return turnerLoopDG[30][col] + 1.75 * 0.6163 * log(size / 30.0);
}


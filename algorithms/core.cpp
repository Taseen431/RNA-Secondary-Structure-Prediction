    out << "---- " << title << " ----\n";
    out << "Iteration: " << r.iteration << "\n";
    out << "Predicted Structure: " << r.structure << "\n";
    out << "Energy: " << r.energy << " kcal/mol\n";
    out << "TP: " << r.metrics.TP << "\n";
    out << "FP: " << r.metrics.FP << "\n";
    out << "FN: " << r.metrics.FN << "\n";
